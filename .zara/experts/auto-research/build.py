#!/usr/bin/env python3
"""Project tracked Org sources into inert, reproducible Prolog data."""
import argparse
import hashlib
import json
import re
import posixpath
import subprocess
from pathlib import Path

KINDS = ('research', 'design', 'implement', 'indexes', 'other')
PREDICATES = ('document/6', 'metadata/3', 'org_id/3', 'tag/2', 'heading/4',
              'passage/3', 'reference/3', 'file_link/3', 'snapshot/1')


def atom(value):
    return "'" + value.replace('\\', '\\\\').replace("'", "\\'").replace('\n', '\\n').replace('\r', '\\r').replace('\t', '\\t') + "'"


def fact(name, *values):
    return name + '(' + ','.join(str(v) if isinstance(v, int) else atom(v) for v in values) + ').\n'


def render(root):
    paths = subprocess.check_output(['git', '-C', str(root), 'ls-files', '-z', '--', 'roam'], text=True).split('\0')
    output = {kind + '.pl': '% Generated by dotfiles .zara/experts/auto-research/build.py; do not edit.\n' for kind in KINDS}
    hashes = []
    for relative in sorted(p for p in paths if p.endswith('.org')):
        path = root / relative
        if path.is_symlink() or not path.resolve().is_relative_to(root.resolve()):
            raise ValueError(f'unsafe source: {relative}')
        if not path.exists():
            continue
        raw = path.read_bytes()
        text = raw.decode('utf-8')
        digest = hashlib.sha256(raw).hexdigest()
        hashes.append(relative + '\0' + digest)
        parts = Path(relative).parts
        kind = parts[1] if len(parts) > 2 and parts[1] in KINDS else 'other'
        project = parts[2] if len(parts) > 3 else '(root)'
        lines = text.splitlines(keepends=True)
        metadata = []
        ids = []
        headings = []
        in_block = False
        header = True
        for number, line in enumerate(lines, 1):
            lowered = line.strip().lower()
            if lowered.startswith('#+begin_'):
                in_block = True
            elif lowered.startswith('#+end_'):
                in_block = False
                continue
            if in_block:
                continue
            heading = re.match(r'^(\*+)\s+(.*?)\s*$', line)
            if heading:
                header = False
                headings.append((number, len(heading[1]), heading[2]))
            match = re.match(r'^\s*#\+([\w-]+):\s*(.*?)\s*$', line)
            if match and header:
                metadata.append((match[1].lower(), match[2]))
            identity = re.match(r'^\s*:ID:\s+(\S+)\s*$', line, re.I)
            if identity:
                ids.append((number, identity[1]))
        values = dict(metadata)
        data = fact('document', relative, kind, project, values.get('title', path.stem), values.get('status', 'MISSING'), digest)
        for key, value in metadata:
            data += fact('metadata', relative, key, value)
        for number, identity in ids:
            data += fact('org_id', relative, number, identity)
        for tag in values.get('filetags', '').strip(':').split(':'):
            if tag:
                data += fact('tag', relative, tag)
        for number, level, title in headings:
            data += fact('heading', relative, number, level, title)
        # Include the full source, including code blocks, exclusively as quoted data.
        boundaries = [1] + [n for n, _, _ in headings if n != 1] + [len(lines) + 1]
        for start, end in zip(boundaries, boundaries[1:]):
            data += fact('passage', relative, start, ''.join(lines[start - 1:end - 1]))
        for number, line in enumerate(lines, 1):
            for target in re.findall(r'\[\[([^\]\n]+)\]', line):
                data += fact('reference', relative, number, target)
                if target.startswith('file:'):
                    destination = target[5:].split('::', 1)[0]
                    if destination.endswith('.org'):
                        resolved = posixpath.normpath(posixpath.join(str(Path(relative).parent), destination))
                        data += fact('file_link', relative, number, resolved)
        output[kind + '.pl'] += data
    snapshot = hashlib.sha256('\n'.join(hashes).encode()).hexdigest()
    output['index.pl'] = (':- module(auto_research_kb, [' + ', '.join(PREDICATES) + ']).\n'
        + ''.join(':- discontiguous ' + p + '.\n:- dynamic ' + p + '.\n' for p in PREDICATES)
        + fact('snapshot', snapshot)
        + ''.join(f":- include('{kind}.pl').\n" for kind in KINDS))
    output["manifest.json"] = json.dumps({"sources": dict(item.split("\0", 1) for item in hashes),
        "outputs": {name: hashlib.sha256(text.encode()).hexdigest() for name, text in output.items()}}, sort_keys=True, indent=2) + "\n"
    return output


def write(root, output, check):
    expected = render(root)
    stale = {p.name for p in output.glob('*') if p.is_file()} - set(expected)
    changed = sorted(name for name, text in expected.items()
                     if not (output / name).is_file() or (output / name).read_text() != text)
    if check:
        if changed or stale:
            print('stale Prolog mirror: ' + ', '.join(sorted(set(changed) | stale)))
        return bool(changed or stale)
    output.mkdir(parents=True, exist_ok=True)
    for name in stale:
        (output / name).unlink()
    for name in changed:
        (output / name).write_text(expected[name], encoding='utf-8')
    return False


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path, required=True)
    parser.add_argument('--output', type=Path)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    output = args.output or args.source / '.prolog/kb/mirror'
    return int(write(args.source.resolve(), output.resolve(), args.check))


if __name__ == '__main__':
    raise SystemExit(main())
